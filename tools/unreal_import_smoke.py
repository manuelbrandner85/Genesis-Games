"""GENESIS UE Editor Python smoke import; run WITHIN open UE Editor Python context.
Example from console: exec(open(r'PATH_TO_THIS_SCRIPT').read())
Set environment GENESIS_SMOKE_FBX to full file path generated by blender_smoke_crate.py.
Only proves import when executed and results verified in Unreal Editor.
"""
import os
import unreal
src=os.environ.get('GENESIS_SMOKE_FBX')
if not src or not os.path.isfile(src):
    raise RuntimeError('Set GENESIS_SMOKE_FBX to existing smoke crate .fbx')
destination='/Game/Genesis/Prototyping/SMOKE_TEST'
asset_tools=unreal.AssetToolsHelpers.get_asset_tools()
t=unreal.AssetImportTask()
t.set_editor_property('filename',src)
t.set_editor_property('destination_path',destination)
t.set_editor_property('automated',True)
t.set_editor_property('save',True)
t.set_editor_property('replace_existing',False)
asset_tools.import_asset_tasks([t])
paths=list(t.get_editor_property('imported_object_paths'))
if not paths:
    raise RuntimeError('Unreal import task returned no assets')
for path in paths:
    obj=unreal.load_asset(path)
    if obj is None:
        raise RuntimeError('Asset readback failed: '+path)
    unreal.log('GENESIS_SMOKE_IMPORT_READBACK: '+path+' CLASS: '+obj.get_class().get_name())
print('GENESIS_SMOKE_UNREAL_IMPORTED',paths)
